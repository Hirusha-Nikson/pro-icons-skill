import fs from 'node:fs';
import path from 'node:path';
import * as si from 'simple-icons';
import sharp from 'sharp';
import { zipSync, strToU8 } from 'fflate';

const SKILL = path.resolve('skills/dev-icons');
const GALLERY = path.resolve('gallery');   // GitHub-only preview, NOT part of the skill
const list = JSON.parse(fs.readFileSync('source/icons.json', 'utf8'));

// Simple Icons exports objects like siReact → index them by slug
const bySlug = {};
for (const icon of Object.values(si)) if (icon && icon.slug) bySlug[icon.slug] = icon;

const THEMES = ['dark', 'light', 'brand'];
const DARK_BG = '#242938';
const LIGHT_BG = '#F4F2ED';
const PNG_SIZES = [128, 512];          // 128 for docs, 512 for slides/video
const ZIP_DATE = new Date('2020-01-01T00:00:00Z');  // fixed, so an unchanged rebuild gives an identical zip

// relative brightness of a hex colour (0 = black, 1 = white)
function luminance(hex) {
  const [r, g, b] = [0, 2, 4].map(i => {
    const c = parseInt(hex.slice(i, i + 2), 16) / 255;
    return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/"/g, '&quot;');

function tileSvg(icon, theme) {
  const brand = '#' + icon.hex;
  const L = luminance(icon.hex);
  let bg, fg;
  if (theme === 'dark')  { bg = DARK_BG;  fg = L < 0.12 ? '#FFFFFF' : brand; }
  if (theme === 'light') { bg = LIGHT_BG; fg = L > 0.70 ? DARK_BG  : brand; }
  if (theme === 'brand') { bg = brand;    fg = L > 0.50 ? '#000000' : '#FFFFFF'; }
  // icon paths are 24×24 → scale ×6 = 144px, centred in a 256px tile
  return `<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256" role="img" aria-label="${esc(icon.title)}"><title>${esc(icon.title)}</title><rect width="256" height="256" rx="60" fill="${bg}"/><g transform="translate(56 56) scale(6)"><path d="${icon.path}" fill="${fg}"/></g></svg>`;
}

const manifest = [];
const missing = [];
const zipFiles = {};   // path inside assets.zip → [bytes, options]

// the gallery is fully generated, so start it fresh each build
fs.rmSync(GALLERY, { recursive: true, force: true });
for (const theme of THEMES) fs.mkdirSync(path.join(GALLERY, theme), { recursive: true });

for (const item of list) {
  const icon = bySlug[item.slug];
  if (!icon) { missing.push(`${item.id} (slug "${item.slug}")`); continue; }

  for (const theme of THEMES) {
    const svg = tileSvg(icon, theme);
    zipFiles[`icons/${theme}/${item.id}.svg`] = [strToU8(svg), { level: 9, mtime: ZIP_DATE }];
    fs.writeFileSync(path.join(GALLERY, theme, `${item.id}.svg`), svg);
    for (const size of PNG_SIZES) {
      const png = await sharp(Buffer.from(svg)).resize(size, size).png().toBuffer();
      zipFiles[`png/${theme}/${size}/${item.id}.png`] = [png, { level: 9, mtime: ZIP_DATE }];
    }
  }
  manifest.push({
    id: item.id, name: item.name, category: item.category,
    aliases: item.aliases, hex: '#' + icon.hex, source: 'simple-icons',
    // null = Simple Icons has no licence data for this logo (which does NOT mean it's free to use)
    license: icon.license ? icon.license.type : null,
    guidelines: icon.guidelines || null
  });
}

fs.writeFileSync(path.join(SKILL, 'assets.zip'), zipSync(zipFiles));
fs.writeFileSync(path.join(SKILL, 'manifest.json'), JSON.stringify(manifest, null, 2));

// gallery/README.md: GitHub renders this when someone opens the gallery folder
const categories = [...new Set(manifest.map(m => m.category))].sort();
const cell = (theme, id, name) => `<img src="${theme}/${id}.svg" width="48" alt="${esc(name)}">`;
let md = `# Icon gallery\n\n${manifest.length} icons in 3 themes (dark, light, brand). ` +
  `Use the **id** with the skill's scripts, e.g. \`compose.py react,ts -o stack.svg\`.\n\n` +
  `> Generated by \`npm run build\`. Don't edit this folder by hand. It is not part of the skill.\n\n` +
  `Logos are from [Simple Icons](https://simpleicons.org) and are trademarks of their owners. ` +
  `Licences vary per logo; "-" means Simple Icons has no licence data, which does not mean it's free to use.\n\n` +
  categories.map(c => `[${c}](#${c})`).join(' · ') + '\n';
for (const cat of categories) {
  md += `\n## ${cat}\n\n| Dark | Light | Brand | id | Name | Aliases | Licence | Brand guidelines |\n|:-:|:-:|:-:|---|---|---|---|---|\n`;
  for (const m of manifest.filter(m => m.category === cat)) {
    const guide = m.guidelines ? `[link](${m.guidelines})` : '-';
    md += `| ${THEMES.map(t => cell(t, m.id, m.name)).join(' | ')} | \`${m.id}\` | ${m.name} | ${m.aliases.join(', ') || '-'} | ${m.license || '-'} | ${guide} |\n`;
  }
}
fs.writeFileSync(path.join(GALLERY, 'README.md'), md);

console.log(`✔ Built ${manifest.length} icons × ${THEMES.length} themes → skills/dev-icons/assets.zip + gallery/`);
if (missing.length) console.log(`✘ Not found in Simple Icons:\n  - ${missing.join('\n  - ')}`);
